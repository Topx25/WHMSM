define('SMPRO_SP_LOG', '/var/log/exim_mainlog');

function smpro_sp_users() { $u = []; foreach (glob('/var/cpanel/users/*') ?: [] as $f) { $b = basename($f); if (preg_match('/^[a-zA-Z0-9._-]+$/', $b)) $u[] = $b; } sort($u); return $u; }

/** Read the last $lines of exim_mainlog INCLUDING rotated generations (see smpro_syslog_read_cmd: budgeted, so
 *  a busy server with huge rotated logs reads the live file only). exim rotates weekly on a stock cPanel box, so
 *  a live-file-only tail silently narrowed every "recent mail activity" view to whatever the live file held —
 *  as little as a day on a busy server, and on a QUIET server the exact case where "no spam" and "log rotated
 *  away" look identical. Falls back to the bare live tail if the shared helper is unavailable. */
function smpro_sp_tail(int $lines, int $days = 7): string {
    if (!is_readable(SMPRO_SP_LOG)) return '';
    $cat = function_exists('smpro_syslog_read_cmd') ? smpro_syslog_read_cmd(SMPRO_SP_LOG, $days) : '';
    $inner = $cat !== '' ? $cat . ' | tail -n ' . (int)$lines
                         : 'tail -n ' . (int)$lines . ' ' . escapeshellarg(SMPRO_SP_LOG);
    return (string)@shell_exec('timeout 40 nice -n ' . SMPRO_SCAN_NICE . ' sh -c ' . escapeshellarg($inner) . ' 2>/dev/null');
}

/** Same window as smpro_sp_tail, streamed line by line (generator — iterate once). The string form held up to
 *  800k exim lines twice in memory and died under the cPanel CLI's 128M cap; this holds one line. */
function smpro_sp_lines(int $lines, int $days = 7): \Generator {
    if (!is_readable(SMPRO_SP_LOG)) return;
    $cat = function_exists('smpro_syslog_read_cmd') ? smpro_syslog_read_cmd(SMPRO_SP_LOG, $days) : '';
    $inner = $cat !== '' ? $cat . ' | tail -n ' . (int)$lines
                         : 'tail -n ' . (int)$lines . ' ' . escapeshellarg(SMPRO_SP_LOG);
    yield from smpro_run_lines('nice -n ' . SMPRO_SCAN_NICE . ' sh -c ' . escapeshellarg($inner), 40);
}

/** Parse a bounded tail of exim_mainlog for sending scripts + senders. */
function smpro_sp_mail_stats($lines) {
    $lines = max(50000, min(800000, (int)$lines));
    $out = ['total' => 0, 'scripts' => [], 'senders' => [], 'accounts' => []];
    if (!is_readable(SMPRO_SP_LOG)) return $out;
    // sending scripts: cwd=/home/<acct>/...  (one per outbound generated by a local script)
    foreach (smpro_sp_lines((int)$lines) as $l) {
        if ($l === '') continue;
        if (strpos($l, '<= ') !== false) {
            $out['total']++;
            if (preg_match('/<=\s+(\S+@\S+)/', $l, $m)) { $s = strtolower($m[1]); $out['senders'][$s] = ($out['senders'][$s] ?? 0) + 1; }
        }
        if (preg_match('#cwd=(/home/([a-zA-Z0-9._-]+)[^\s]*)#', $l, $m)) {
            $acct = $m[2]; $cwd = $m[1];
            if (!isset($out['scripts'][$cwd])) $out['scripts'][$cwd] = ['account' => $acct, 'cwd' => $cwd, 'count' => 0];
            $out['scripts'][$cwd]['count']++;
            $out['accounts'][$acct] = ($out['accounts'][$acct] ?? 0) + 1;
        }
    }
    uasort($out['scripts'], fn($a, $b) => $b['count'] <=> $a['count']);
    arsort($out['senders']); arsort($out['accounts']);
    return $out;
}

