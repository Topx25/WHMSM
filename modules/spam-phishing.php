/**
 * Deep-scan one account's OUTGOING mail from a bounded exim_mainlog tail.
 * Returns per-message delivery events, subject grouping, internal/external recipient
 * breakdown, and explainable spam SIGNALS + a score (the basis for the auto-learning model).
 */
function smpro_sp_mail_scan($account, $lines) {
    $srv = smpro_sp_server_domains();
    $acctDoms = array_fill_keys(array_keys(array_filter($srv, fn($u) => $u === $account)), 1);
    $msgs = []; $pendCwd = '';   // cPanel logs "cwd=/home/<acct> … args: sendmail" on the line BEFORE the <= arrival
    foreach ($lines as $l) {
        if (strpos($l, ' <= ') !== false) {
            if (!preg_match('/^(\S+ \S+) (\S+) <= (\S+)/', $l, $m)) continue;
            $cwdAcct = preg_match('#\bcwd=/home/([a-zA-Z0-9._-]+)#', $l, $mc) ? $mc[1] : $pendCwd;   // inline OR preceding cwd line
            $pendCwd = '';
            $auth = preg_match('/\bA=[a-z0-9_]+:([^\s]+@[^\s]+)/i', $l, $ma) ? strtolower($ma[1]) : '';
            $authDom = $auth !== '' ? strtolower((string)substr(strrchr($auth, '@'), 1)) : '';
            if (!(($cwdAcct === $account) || ($authDom !== '' && isset($acctDoms[$authDom])))) continue;
            $msgs[$m[2]] = ['id'=>$m[2],'ts'=>strtotime($m[1]),'from'=>$m[3],'auth'=>$auth,'cwd'=>$cwdAcct ? smpro_user_home($cwdAcct) : '',
                'subj'=> preg_match('/\bT="((?:[^"\\\\]|\\\\.)*)"/', $l, $mt) ? smpro_sp_decode_subject($mt[1]) : '',
                'size'=> preg_match('/\bS=(\d+)/', $l, $ms) ? (int)$ms[1] : 0, 'rcpts'=>[], 'events'=>[]];
        } elseif (strpos($l, ' cwd=/home/') !== false && preg_match('/^\S+ \S+ cwd=\/home\/([a-zA-Z0-9._-]+)/', $l, $mp)) {
            $pendCwd = $mp[1];   // remember for the very next arrival line
        } elseif (preg_match('/^(\S+ \S+) (\S+) (=>|->|>>|\*\*|==) (.+)$/', $l, $m)) {
            $id = $m[2]; if (!isset($msgs[$id])) continue;
            $addr = preg_match('/<?([^\s<>]+@[^\s<>]+)>?/', $m[4], $mr) ? strtolower($mr[1]) : trim(explode(' ', $m[4])[0]);
            $dom = strtolower((string)substr(strrchr($addr, '@') ?: '', 1));
            $st = ['=>'=>'delivered','->'=>'delivered','>>'=>'cc-delivered','**'=>'bounced','=='=>'deferred'][$m[3]] ?? 'event';
            $internal = $dom !== '' && isset($srv[$dom]);
            $msgs[$id]['rcpts'][] = ['addr'=>$addr,'internal'=>$internal,'status'=>$st];
            if (count($msgs[$id]['events']) < 25) $msgs[$id]['events'][] = ['ts'=>strtotime($m[1]),'status'=>$st,'addr'=>$addr,'internal'=>$internal];
        }
    }
    // aggregate
    $subjAgg = []; $totMsg = 0; $totRcpt = 0; $intRcpt = 0; $rcptSet = [];
    foreach ($msgs as $mm) {
        $totMsg++;
        foreach ($mm['rcpts'] as $r) { $totRcpt++; $rcptSet[$r['addr']] = 1; if ($r['internal']) $intRcpt++; }
        $k = $mm['subj'] !== '' ? $mm['subj'] : '(no subject)';
        if (!isset($subjAgg[$k])) $subjAgg[$k] = ['subj'=>$k,'count'=>0,'rcpts'=>0];
        $subjAgg[$k]['count']++; $subjAgg[$k]['rcpts'] += count($mm['rcpts']);
    }
    usort($subjAgg, fn($a, $b) => $b['count'] <=> $a['count']);
    $extRcpt = $totRcpt - $intRcpt;
    // explainable spam signals (this is the transparent model the auto-learning tunes)
    $sig = [];
    if ($totMsg >= 100) $sig[] = ['t'=>'High outbound volume — '.$totMsg.' messages in the window','w'=>3];
    if ($totRcpt >= 50 && $extRcpt / max(1,$totRcpt) >= 0.9) $sig[] = ['t'=>'Almost all recipients external ('.round($extRcpt/max(1,$totRcpt)*100).'%) — typical of a blast','w'=>2];
    if ($subjAgg && $subjAgg[0]['count'] >= 50) $sig[] = ['t'=>'Mass identical subject ×'.$subjAgg[0]['count'].' — "'.mb_substr($subjAgg[0]['subj'],0,46).'"','w'=>3];
    if (count($rcptSet) >= 200) $sig[] = ['t'=>'Large recipient fan-out — '.count($rcptSet).' distinct addresses','w'=>2];
    $kw = 0; foreach ($subjAgg as $s) foreach (smpro_sp_spam_keywords() as $w) if (stripos($s['subj'], $w) !== false) { $kw++; break; }
    if ($kw) $sig[] = ['t'=>$kw.' subject(s) match known spam keywords','w'=>2];
    if ($intRcpt > 0 && $extRcpt === 0 && $totMsg < 50) $sig[] = ['t'=>'Internal-only, low volume — looks legitimate','w'=>-2];
    $score = max(0, array_sum(array_map(fn($x) => $x['w'], $sig)));
    $verdict = $score >= 6 ? 'high' : ($score >= 3 ? 'suspicious' : 'low');
    usort($msgs, fn($a, $b) => $b['ts'] <=> $a['ts']);
    return ['account'=>$account,'total_msgs'=>$totMsg,'total_rcpts'=>$totRcpt,'internal'=>$intRcpt,'external'=>$extRcpt,
        'distinct_rcpts'=>count($rcptSet),'distinct_subjects'=>count($subjAgg),
        'subjects'=>array_slice($subjAgg,0,25),'signals'=>$sig,'score'=>$score,'verdict'=>$verdict,
        'messages'=>array_slice(array_values($msgs),0,40)];
}

/**
 * Gather REAL forensic evidence for the AI so it can do an actual investigation instead of a
 * generic "investigate further": (A) the account's mail-log statistics (subjects, recipient
 * fan-out, external ratio, heuristic signals, sample messages) via the existing deep scanner, and
 * (B) the actual suspect PHP files in the account home (recently-modified, matching mailer /
 * obfuscation signatures) with content snippets — so the model can name the file and explain what
 * it does. Bounded: find/grep run under timeout + nice + ionice. Content is redacted by the caller.
 */
function smpro_sp_ai_evidence($account, $win = 200000) {
    $account = preg_replace('/[^a-z0-9._-]/i', '', (string) $account);
    if ($account === '') return "No cPanel account could be resolved from the exim cwd.";
    $home = smpro_user_home($account);
    $out  = '';

    // (A) mail-log evidence via the existing per-account deep scanner
    if (is_readable(SMPRO_SP_LOG)) {
        $sc = smpro_sp_mail_scan($account, smpro_sp_lines((int)$win));
        $out .= "MAIL-LOG EVIDENCE (account '$account'):\n";
        $out .= "  messages={$sc['total_msgs']} recipients={$sc['total_rcpts']} distinct_recipients={$sc['distinct_rcpts']} external={$sc['external']} internal={$sc['internal']} heuristic_score={$sc['score']} ({$sc['verdict']})\n";
        if ($sc['signals']) $out .= "  signals: " . implode('; ', array_map(fn($x) => $x['t'], $sc['signals'])) . "\n";
        if ($sc['subjects']) {
            $out .= "  top subjects:\n";
            foreach (array_slice($sc['subjects'], 0, 8) as $s) $out .= "    x{$s['count']}  " . mb_substr($s['subj'], 0, 90) . "\n";
        }
        if ($sc['messages']) {
            $out .= "  sample messages (envelope-from -> first recipients):\n";
            foreach (array_slice($sc['messages'], 0, 5) as $m) {
                $rc = implode(', ', array_slice(array_map(fn($r) => $r['addr'], $m['rcpts']), 0, 3));
                $out .= "    {$m['from']}  \"" . mb_substr($m['subj'], 0, 50) . "\"  -> " . $rc . "\n";
            }
        }
    }

    // (B) suspect files: recently-modified PHP matching mailer / obfuscation signatures
    if (is_dir($home)) {
        $sigRe = 'mail\(|mb_send_mail|->[Ss]end\(|PHPMailer|fsockopen|stream_socket_client|base64_decode|gz(inflate|uncompress)|str_rot13|eval\(|assert\(|create_function|preg_replace\([^)]*/e|\$_(POST|GET|REQUEST)\[';
        $pipeline = 'cd ' . escapeshellarg($home) . ' && find . -type f \\( -name "*.php" -o -name "*.phtml" -o -name "*.inc" \\) -mtime -90 '
                  . '-not -path "*/wp-admin/*" -not -path "*/wp-includes/*" -not -path "*/vendor/*" -not -path "*/node_modules/*" -not -path "*/cache/*" '
                  . '2>/dev/null | head -6000 | xargs -r grep -lE ' . escapeshellarg($sigRe) . ' 2>/dev/null | head -80';
        $cmd = 'timeout 35 nice -n ' . SMPRO_SCAN_NICE . ' ionice -c3 bash -c ' . escapeshellarg($pipeline);
        $found = array_filter(array_map('trim', explode("\n", (string) @shell_exec($cmd))));
        // rank by SUSPICION (obfuscation signatures + recency) so real droppers float above legit WP core files
        $strong = ['eval(', 'base64_decode', 'gzinflate', 'gzuncompress', 'str_rot13', 'assert(', 'create_function', 'preg_replace'];
        $scored = [];
        foreach ($found as $rel) {
            $full = $home . '/' . ltrim($rel, './');
            if (!is_file($full) || !is_readable($full)) continue;
            if (function_exists('smpro_wpguard_trusted') && smpro_wpguard_trusted($full)) continue;   // WP Guard's own security code names these signatures; its quarantine holds real payloads — both trusted
            $head = (string) @file_get_contents($full, false, null, 0, 4000);
            $s = 0; foreach ($strong as $t) if (stripos($head, $t) !== false) $s += 3;
            if (stripos($head, 'mail(') !== false || stripos($head, 'mb_send_mail') !== false) $s += 1;
            $mt = @filemtime($full) ?: 0; if ($mt > time() - 14 * 86400) $s += 2;   // recently dropped
            $scored[$full] = ['s' => $s, 'mt' => $mt];
        }
        uasort($scored, fn($a, $b) => ($b['s'] <=> $a['s']) ?: ($b['mt'] <=> $a['mt']));
        $top = array_slice(array_keys($scored), 0, 5);
        if ($top) {
            $out .= "\nSUSPECT FILES (PHP matching mailer/obfuscation signatures, ranked by suspicion then recency — " . count($scored) . " matched, showing " . count($top) . "):\n";
            foreach ($top as $full) {
                $snip = (string) @file_get_contents($full, false, null, 0, 2600);
                $hit  = [];
                foreach (['mail(', 'mb_send_mail', 'base64_decode', 'gzinflate', 'gzuncompress', 'str_rot13', 'eval(', 'assert(', 'create_function', 'fsockopen', 'PHPMailer', '$_POST', '$_GET', '$_REQUEST', 'preg_replace'] as $s) {
                    if (stripos($snip, $s) !== false) $hit[] = $s;
                }
                $out .= "\n--- FILE: $full  (size=" . (int) @filesize($full) . "B, modified=" . @date('Y-m-d H:i', @filemtime($full)) . ", matched: " . implode(' ', $hit) . ") ---\n";
                $out .= rtrim(substr($snip, 0, 2200)) . "\n";
            }
        } else {
            $out .= "\nSUSPECT FILES: no PHP file modified in the last 90 days in $home matched mailer/obfuscation signatures. The mailer may be older, outside the home dir, or the mail is sent via authenticated SMTP (a compromised mailbox rather than a script).\n";
        }
    } else {
        $out .= "\n(Home directory $home not found or unreadable — file scan skipped.)\n";
    }
    return $out !== '' ? $out : "No evidence could be gathered for account '$account'.";
}

