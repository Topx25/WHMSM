/* ---------- Account-level outgoing-mail block (POST+CSRF+root) via cPanel's native suspension file ----------
 * /etc/outgoing_mail_suspended_users is exactly what WHM's "Manage Outgoing Email Suspensions" writes; exim
 * reads it live (no restart), so this stops ALL of the account's outgoing mail (every mailbox + local scripts)
 * while the website keeps running. Reversible. License-independent (does not depend on whmapi1 being healthy). */
function smpro_sp_acct_outgoing_suspend($acct, $block) {
    $file = '/etc/outgoing_mail_suspended_users';
    $fp = @fopen($file, 'c+');
    if ($fp === false) return ['ok' => false, 'msg' => 'Cannot open ' . $file . ' — check permissions.'];
    if (!@flock($fp, LOCK_EX)) { @fclose($fp); return ['ok' => false, 'msg' => 'Could not lock the suspension file (busy).']; }
    $raw   = (string) stream_get_contents($fp);
    $lines = array_values(array_unique(array_filter(array_map('trim', explode("\n", $raw)), 'strlen')));
    $had   = in_array($acct, $lines, true);
    if ($block) { if (!$had) $lines[] = $acct; }
    else        { $lines = array_values(array_filter($lines, function ($u) use ($acct) { return $u !== $acct; })); }
    sort($lines);
    $out = $lines ? (implode("\n", $lines) . "\n") : '';
    @rewind($fp); @ftruncate($fp, 0); $w = @fwrite($fp, $out); @fflush($fp);
    @flock($fp, LOCK_UN); @fclose($fp); @chmod($file, 0644);
    if ($w === false) return ['ok' => false, 'msg' => 'Write failed on ' . $file . '.'];
    return ['ok' => true, 'blocked' => $block, 'msg' => $block
        ? ('Outgoing mail BLOCKED for the whole account "' . $acct . '" (reversible). The website keeps running — only sending is stopped.')
        : ('Outgoing mail RESTORED for "' . $acct . '".')];
}
