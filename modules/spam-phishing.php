/** Resolve the cPanel account owning an email address or domain (via /etc/userdomains). */
function smpro_sp_owner($emailOrDomain) {
    static $map = null;
    if ($map === null) { $map = []; if (is_readable('/etc/userdomains')) foreach (file('/etc/userdomains', FILE_IGNORE_NEW_LINES) ?: [] as $ln) if (preg_match('/^([^:]+):\s*(\S+)/', $ln, $m)) $map[strtolower(trim($m[1]))] = trim($m[2]); }
    $id = strtolower(trim((string)$emailOrDomain));
    $dom = strpos($id, '@') !== false ? substr(strrchr($id, '@'), 1) : $id;
    return $map[$dom] ?? '';
}

/** Every message currently in the Exim queue (so the admin can SEE them before deleting).
 *  Parses `exim -bp`: a header line "age size msgid <sender> [*** frozen ***]" followed by indented recipients. */
function smpro_sp_queue_messages($limit = 500) {
    $exim = is_executable('/usr/sbin/exim') ? '/usr/sbin/exim' : (is_executable('/usr/bin/exim') ? '/usr/bin/exim' : '');
    if ($exim === '') return [];
    $raw = (string)@shell_exec('timeout 60 ' . $exim . ' -bp 2>/dev/null | head -n ' . ((int)$limit * 8));
    if (trim($raw) === '') return [];
    $msgs = []; $cur = null;
    foreach (explode("\n", $raw) as $ln) {
        if (trim($ln) === '') continue;
        if (preg_match('/^\s*(\S+)\s+(\S+)\s+([0-9A-Za-z]{6}-[0-9A-Za-z]{6,}-[0-9A-Za-z]{2,})\s+(<[^>]*>|\S+)(.*)$/', $ln, $m)) {
            if ($cur) { $msgs[] = $cur; if (count($msgs) >= $limit) { $cur = null; break; } }
            $sender = trim($m[4], '<>'); if ($sender === '') $sender = '<>';
            $cur = ['age'=>$m[1], 'size'=>$m[2], 'id'=>$m[3], 'sender'=>$sender, 'frozen'=>(stripos($m[5], 'frozen') !== false), 'rcpts'=>[]];
        } elseif ($cur !== null && preg_match('/^\s+(\S+@\S+|[A-Za-z0-9._%+\-\/]+)\s*$/', $ln, $rm)) {
            if (count($cur['rcpts']) < 25) $cur['rcpts'][] = trim($rm[1]);
        }
    }
    if ($cur !== null && count($msgs) < $limit) $msgs[] = $cur;
    return $msgs;
}
/** Every frozen message id in the queue through exiqgrep (no cap); null when exiqgrep is not installed. */
function smpro_sp_frozen_ids(string $exim): ?array {
    $g = is_executable('/usr/sbin/exiqgrep') ? '/usr/sbin/exiqgrep' : (is_executable('/usr/bin/exiqgrep') ? '/usr/bin/exiqgrep' : '');
    if ($g === '') return null;
    $out = (string)@shell_exec('timeout 120 ' . $g . ' -z -i 2>/dev/null');
    $ids = [];
    foreach (preg_split('/\r?\n/', trim($out)) as $l) { $l = trim($l); if ($l !== '' && smpro_sp_valid_msgid($l)) $ids[] = $l; }
    return $ids;
}
/** Validate an Exim message-id. */
/** Exim message id. Legacy is 6-6-2; Exim 4.97+ (cPanel 11.136 ships 4.99) uses a LONGER middle and tail —
 *  e.g. 1wnyZN-00000007Q4y-3WB0. Pinning the old widths made every modern id fail validation, which silently
 *  disabled queue review and the frozen-mail purge. Accept both; the charset still keeps it shell-safe. */
function smpro_sp_valid_msgid($id) { return (bool)preg_match('/^[0-9A-Za-z]{6}-[0-9A-Za-z]{6,}-[0-9A-Za-z]{2,}$/', (string)$id); }

/** Exim mail-queue snapshot: total, frozen, and top senders in the queue. */
function smpro_sp_queue() {
    $exim = is_executable('/usr/sbin/exim') ? '/usr/sbin/exim' : (is_executable('/usr/bin/exim') ? '/usr/bin/exim' : '');
    $out = ['exim' => $exim !== '', 'count' => 0, 'frozen' => 0, 'senders' => [], 'sample' => []];
    if ($exim === '') return $out;
    $out['count'] = (int)trim((string)@shell_exec('timeout 20 ' . $exim . ' -bpc 2>/dev/null'));
    $raw = (string)@shell_exec('timeout 30 ' . $exim . ' -bp 2>/dev/null | head -4000');
    foreach (explode("\n", $raw) as $l) {
        // " 5d   83K 1wWcyW-...-1jII <sender@dom> *** frozen ***"
        if (!preg_match('/^\s*\S+\s+\S+\s+(\S+)\s+<([^>]*)>(.*)$/', $l, $m)) continue;
        $sender = strtolower($m[2]); $frozen = stripos($m[3], 'frozen') !== false;
        if ($frozen) $out['frozen']++;
        // Empty-sender messages (<>) are bounces/DSNs — the common case for a queue full of frozen spam. Bucket
        // them under "<>" so the queue is NEVER shown as empty when it actually holds messages (was the bug where
        // "31 frozen" displayed "queue is empty / clean" because every message had no envelope sender).
        $key = $sender !== '' ? $sender : '<>';
        if (!isset($out['senders'][$key])) $out['senders'][$key] = ['count' => 0, 'frozen' => 0];
        $out['senders'][$key]['count']++; if ($frozen) $out['senders'][$key]['frozen']++;
    }
    uasort($out['senders'], fn($a, $b) => $b['count'] <=> $a['count']);
    return $out;
}

/** Authenticated SMTP senders by source IP — a remote IP that logged into a local
 *  mailbox and is sending mail. The real "block this IP" candidates (legit inbound
 *  relays like gmail/icloud are NOT authenticated, so they never appear here). */
function smpro_sp_auth_ips($lines) {
    $lines = max(50000, min(800000, (int)$lines));
    $out = [];
    if (!is_readable(SMPRO_SP_LOG)) return $out;
    foreach (smpro_sp_lines((int)$lines) as $l) {
        if (strpos($l, '<= ') === false || strpos($l, ' A=') === false) continue;   // authenticated submissions only
        if (!preg_match('/\[([0-9a-fA-F:.]+)\](?::\d+)?\s/', $l, $mi)) continue;
        $ip = $mi[1];
        if (function_exists('smpro_is_server_ip') && smpro_is_server_ip($ip)) continue;  // never list localhost / the server's own IP
        $sender = preg_match('/<=\s+(\S+)/', $l, $ms) ? strtolower($ms[1]) : '';
        $auth = preg_match('/\bA=(\S+)/', $l, $ma) ? $ma[1] : '';
        $user = $auth !== '' ? (strpos($auth, ':') !== false ? substr(strrchr($auth, ':'), 1) : $auth) : $sender;
        if (!isset($out[$ip])) $out[$ip] = ['ip' => $ip, 'count' => 0, 'users' => []];
        $out[$ip]['count']++; if ($user !== '' && $user !== '-') $out[$ip]['users'][strtolower($user)] = 1;
    }
    uasort($out, fn($a, $b) => $b['count'] <=> $a['count']);
    return $out;
}

/**
 * Outgoing mail grouped by the AUTHENTICATED mailbox (which email account is sending).
 * Returns per-mailbox: counts in the last hour / 24h / window total, last-seen, a spam
 * flag, and a sample of recent messages (time, decoded subject, recipient, size).
 */
function smpro_sp_outgoing($lines, $thrHour = 60) {
    // Accepts either an array of exim log lines OR a line-count window (int) — in the
    // latter case it tails the log itself, same as smpro_sp_mail_stats/smpro_sp_auth_ips.
    if (!is_array($lines)) {
        $n = max(50000, min(800000, (int)$lines));
        if (!is_readable(SMPRO_SP_LOG)) return [];
        $lines = smpro_sp_lines((int)$n);
    }
    $now = time(); $rcpt = []; $arr = []; $by = [];
    foreach ($lines as $l) {
        if (strpos($l, ' => ') !== false || strpos($l, ' -> ') !== false || strpos($l, ' >> ') !== false) {
            if (preg_match('/^\S+ \S+ (\S+) (?:=>|->|>>) (\S+)/', $l, $m)) { $id = $m[1]; if (!isset($rcpt[$id])) $rcpt[$id] = ['n' => 0, 'first' => $m[2]]; $rcpt[$id]['n']++; }
            continue;
        }
        if (strpos($l, ' <= ') === false) continue;
        if (!preg_match('/\bA=[a-z0-9_]+:([^\s]+@[^\s]+)/i', $l, $ma)) continue;   // authenticated mailbox only
        if (!preg_match('/^(\S+ \S+) (\S+) <= (\S+)/', $l, $m)) continue;
        $ts = strtotime($m[1]); $id = $m[2]; $from = $m[3]; $email = strtolower($ma[1]);
        $arr[$id] = ['ts' => $ts, 'from' => $from,
            'subj' => preg_match('/\bT="((?:[^"\\\\]|\\\\.)*)"/', $l, $mt) ? $mt[1] : '',
            'size' => preg_match('/\bS=(\d+)/', $l, $ms) ? (int)$ms[1] : 0];
        if (!isset($by[$email])) $by[$email] = ['total' => 0, 'h1' => 0, 'h24' => 0, 'last' => 0, 'ids' => []];
        $by[$email]['total']++;
        if ($ts) { if ($now - $ts <= 3600) $by[$email]['h1']++; if ($now - $ts <= 86400) $by[$email]['h24']++; if ($ts > $by[$email]['last']) $by[$email]['last'] = $ts; }
        if (count($by[$email]['ids']) < 25) $by[$email]['ids'][] = $id;
    }
    $rows = [];
    foreach ($by as $email => $b) {
        $msgs = [];
        foreach ($b['ids'] as $id) {
            $a = $arr[$id] ?? null; if (!$a) continue; $r = $rcpt[$id] ?? ['n' => 0, 'first' => ''];
            $subj = $a['subj'] !== '' ? smpro_sp_decode_subject($a['subj']) : '';
            $msgs[] = ['ts' => $a['ts'], 'subj' => $subj, 'to' => $r['first'], 'rcpts' => max(1, $r['n']), 'size' => $a['size']];
        }
        usort($msgs, fn($x, $y) => $y['ts'] <=> $x['ts']);
        $rows[] = ['email' => $email, 'owner' => smpro_sp_owner($email), 'total' => $b['total'],
            'h1' => $b['h1'], 'h24' => $b['h24'], 'last' => $b['last'],
            'spam' => ($b['h1'] >= $thrHour || $b['h24'] >= $thrHour * 5), 'msgs' => $msgs];
    }
    usort($rows, fn($a, $b) => ($b['h24'] <=> $a['h24']) ?: ($b['total'] <=> $a['total']));
    return $rows;
}
/**
 * Decode an exim T="…" subject: exim escapes non-ASCII bytes as octal (\ddd), and the
 * underlying text is often MIME-encoded (=?…?=) OR raw Windows-1256 / ISO-8859-6 Arabic.
 * Returns proper UTF-8 (fixes the "\331\342…" garble seen in other tools).
 */
function smpro_sp_decode_subject($t) {
    $s = stripcslashes((string)$t);                       // \ddd octal + \" → raw bytes
    if (strpos($s, '=?') !== false) {                     // MIME-encoded header
        $d = @mb_decode_mimeheader($s);
        if ($d !== false && $d !== '') $s = $d;
    }
    if (!mb_check_encoding($s, 'UTF-8')) {                 // raw 8-bit → most Arabic mail is Windows-1256
        foreach (['Windows-1256', 'ISO-8859-6', 'ISO-8859-1'] as $enc) {
            $c = @iconv($enc, 'UTF-8//TRANSLIT', $s);
            if ($c !== false && mb_check_encoding($c, 'UTF-8')) { $s = $c; break; }
        }
    }
    return $s;
}
/** A strong random mailbox password (upper+lower+digit+symbol). */
function smpro_sp_genpass() {
    $set = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789';
    $s = ''; for ($i = 0; $i < 14; $i++) $s .= $set[random_int(0, strlen($set) - 1)];
    return $s . '#' . random_int(10, 99);
}
/** domain => owner for every hosted domain (so we can tell internal vs external recipients). */
function smpro_sp_server_domains() {
    static $d = null; if ($d !== null) return $d; $d = [];
    foreach (@file('/etc/userdomains', FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $ln) {
        $p = strrpos($ln, ':'); if ($p === false) continue;
        $dom = strtolower(trim(substr($ln, 0, $p))); if ($dom === '' || $dom === '*') continue;
        $d[$dom] = trim(substr($ln, $p + 1));
    }
    return $d;
}
