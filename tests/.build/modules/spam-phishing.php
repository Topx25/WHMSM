/**
 * Deep-scan one account's OUTGOING mail from a bounded exim_mainlog tail.
 * Returns per-message delivery events, subject grouping, internal/external recipient
 * breakdown, and explainable spam SIGNALS + a score (the basis for the auto-learning model).
 */
function smpro_sp_mail_scan($account, $lines) {
    $srv = smpro_sp_server_domains();
    $acctDoms = array_fill_keys(array_keys(array_filter($srv, fn($u) => $u === $account)), 1);
    $msgs = []; $pendCwd = '';   // cPanel logs "cwd=/home/<acct> … args: sendmail" on the line BEFORE the <= arrival
    foreach ($lines as $l) {
        if (strpos($l, ' <= ') !== false) {
            if (!preg_match('/^(\S+ \S+) (\S+) <= (\S+)/', $l, $m)) continue;
            $cwdAcct = preg_match('#\bcwd=/home/([a-zA-Z0-9._-]+)#', $l, $mc) ? $mc[1] : $pendCwd;   // inline OR preceding cwd line
            $pendCwd = '';
            $auth = preg_match('/\bA=[a-z0-9_]+:([^\s]+@[^\s]+)/i', $l, $ma) ? strtolower($ma[1]) : '';
            $authDom = $auth !== '' ? strtolower((string)substr(strrchr($auth, '@'), 1)) : '';
            if (!(($cwdAcct === $account) || ($authDom !== '' && isset($acctDoms[$authDom])))) continue;
            $msgs[$m[2]] = ['id'=>$m[2],'ts'=>strtotime($m[1]),'from'=>$m[3],'auth'=>$auth,'cwd'=>$cwdAcct ? '/home/'.$cwdAcct : '',
                'subj'=> preg_match('/\bT="((?:[^"\\\\]|\\\\.)*)"/', $l, $mt) ? smpro_sp_decode_subject($mt[1]) : '',
                'size'=> preg_match('/\bS=(\d+)/', $l, $ms) ? (int)$ms[1] : 0, 'rcpts'=>[], 'events'=>[]];
        } elseif (strpos($l, ' cwd=/home/') !== false && preg_match('/^\S+ \S+ cwd=\/home\/([a-zA-Z0-9._-]+)/', $l, $mp)) {
            $pendCwd = $mp[1];   // remember for the very next arrival line
        } elseif (preg_match('/^(\S+ \S+) (\S+) (=>|->|>>|\*\*|==) (.+)$/', $l, $m)) {
            $id = $m[2]; if (!isset($msgs[$id])) continue;
            $addr = preg_match('/<?([^\s<>]+@[^\s<>]+)>?/', $m[4], $mr) ? strtolower($mr[1]) : trim(explode(' ', $m[4])[0]);
            $dom = strtolower((string)substr(strrchr($addr, '@') ?: '', 1));
            $st = ['=>'=>'delivered','->'=>'delivered','>>'=>'cc-delivered','**'=>'bounced','=='=>'deferred'][$m[3]] ?? 'event';
            $internal = $dom !== '' && isset($srv[$dom]);
            $msgs[$id]['rcpts'][] = ['addr'=>$addr,'internal'=>$internal,'status'=>$st];
            if (count($msgs[$id]['events']) < 25) $msgs[$id]['events'][] = ['ts'=>strtotime($m[1]),'status'=>$st,'addr'=>$addr,'internal'=>$internal];
        }
    }
    // aggregate
    $subjAgg = []; $totMsg = 0; $totRcpt = 0; $intRcpt = 0; $rcptSet = [];
    foreach ($msgs as $mm) {
        $totMsg++;
        foreach ($mm['rcpts'] as $r) { $totRcpt++; $rcptSet[$r['addr']] = 1; if ($r['internal']) $intRcpt++; }
        $k = $mm['subj'] !== '' ? $mm['subj'] : '(no subject)';
        if (!isset($subjAgg[$k])) $subjAgg[$k] = ['subj'=>$k,'count'=>0,'rcpts'=>0];
        $subjAgg[$k]['count']++; $subjAgg[$k]['rcpts'] += count($mm['rcpts']);
    }
    usort($subjAgg, fn($a, $b) => $b['count'] <=> $a['count']);
    $extRcpt = $totRcpt - $intRcpt;
    // explainable spam signals (this is the transparent model the auto-learning tunes)
    $sig = [];
    if ($totMsg >= 100) $sig[] = ['t'=>'High outbound volume — '.$totMsg.' messages in the window','w'=>3];
    if ($totRcpt >= 50 && $extRcpt / max(1,$totRcpt) >= 0.9) $sig[] = ['t'=>'Almost all recipients external ('.round($extRcpt/max(1,$totRcpt)*100).'%) — typical of a blast','w'=>2];
    if ($subjAgg && $subjAgg[0]['count'] >= 50) $sig[] = ['t'=>'Mass identical subject ×'.$subjAgg[0]['count'].' — "'.mb_substr($subjAgg[0]['subj'],0,46).'"','w'=>3];
    if (count($rcptSet) >= 200) $sig[] = ['t'=>'Large recipient fan-out — '.count($rcptSet).' distinct addresses','w'=>2];
    $kw = 0; foreach ($subjAgg as $s) foreach (smpro_sp_spam_keywords() as $w) if (stripos($s['subj'], $w) !== false) { $kw++; break; }
    if ($kw) $sig[] = ['t'=>$kw.' subject(s) match known spam keywords','w'=>2];
    if ($intRcpt > 0 && $extRcpt === 0 && $totMsg < 50) $sig[] = ['t'=>'Internal-only, low volume — looks legitimate','w'=>-2];
    $score = max(0, array_sum(array_map(fn($x) => $x['w'], $sig)));
    $verdict = $score >= 6 ? 'high' : ($score >= 3 ? 'suspicious' : 'low');
    usort($msgs, fn($a, $b) => $b['ts'] <=> $a['ts']);
    return ['account'=>$account,'total_msgs'=>$totMsg,'total_rcpts'=>$totRcpt,'internal'=>$intRcpt,'external'=>$extRcpt,
        'distinct_rcpts'=>count($rcptSet),'distinct_subjects'=>count($subjAgg),
        'subjects'=>array_slice($subjAgg,0,25),'signals'=>$sig,'score'=>$score,'verdict'=>$verdict,
        'messages'=>array_slice(array_values($msgs),0,40)];
}

/* ---------- AI analysis of a mailer script / phishing page (POST+CSRF+root) ---------- */
$reqMethod = strtoupper((string)($_SERVER['REQUEST_METHOD'] ?? getenv('REQUEST_METHOD') ?: 'GET'));

/* ---------- CSF block of spam-source IP(s) (POST+CSRF+root, multi) ---------- */
if ($reqMethod === 'POST' && ($_POST['sp_action'] ?? '') === 'csf_block') {
    smpro_require_valid_csrf('sp_ai'); smpro_require_root();
    header('Content-Type: application/json');
    $csf = is_executable('/usr/sbin/csf') ? '/usr/sbin/csf' : '/usr/local/csf/bin/csf';
    if (!is_executable($csf)) { echo json_encode(['ok' => false, 'msg' => 'csf not found.']); exit; }
    $myIp = function_exists('smpro_current_remote_ip') ? smpro_current_remote_ip() : '';
    $ips = array_unique(array_filter(array_map('trim', explode(',', (string)($_POST['ips'] ?? '')))));
    $res = [];
    foreach ($ips as $ip) {
        if (!filter_var($ip, FILTER_VALIDATE_IP)) { $res[] = ['ip' => $ip, 'ok' => false, 'msg' => 'invalid IP']; continue; }
        if (function_exists('smpro_is_server_ip') && smpro_is_server_ip($ip)) { $res[] = ['ip' => $ip, 'ok' => false, 'msg' => 'refused: this is the server / localhost IP']; continue; }
        if (function_exists('smpro_ip_is_external') && !smpro_ip_is_external($ip)) { $res[] = ['ip' => $ip, 'ok' => false, 'msg' => 'refused: private/local IP']; continue; }
        if ($ip === $myIp) { $res[] = ['ip' => $ip, 'ok' => false, 'msg' => 'refused: your own IP']; continue; }
        $out = (string)@shell_exec('timeout 25 ' . escapeshellarg($csf) . ' -d ' . escapeshellarg($ip) . ' ' . escapeshellarg('smpro Spam ' . date('Y-m-d H:i')) . ' 2>&1');
        $ok = stripos($out, 'error') === false && trim($out) !== '';
        smpro_audit('spam_csf_block', ['ip' => $ip, 'ok' => $ok]);
        $res[] = ['ip' => $ip, 'ok' => $ok, 'msg' => $ok ? 'blocked' : trim(mb_substr($out, 0, 120))];
    }
    $okN = count(array_filter($res, fn($r) => $r['ok']));
    echo json_encode(['ok' => $okN > 0, 'msg' => 'Blocked ' . $okN . '/' . count($res) . ' IP(s) in CSF firewall.', 'results' => $res], JSON_UNESCAPED_SLASHES); exit;
}

/* ---------- Mail queue control (POST+CSRF+root): remove frozen / remove by sender ---------- */
if ($reqMethod === 'POST' && in_array(($_POST['sp_action'] ?? ''), ['queue_rm_frozen', 'queue_rm_sender'], true)) {
    smpro_require_valid_csrf('sp_ai'); smpro_require_root();
    header('Content-Type: application/json');
    $exim = is_executable('/usr/sbin/exim') ? '/usr/sbin/exim' : '/usr/bin/exim';
    if (!is_executable($exim)) { echo json_encode(['ok' => false, 'msg' => 'exim not found.']); exit; }
    if ($_POST['sp_action'] === 'queue_rm_frozen') {
        $n = (int)trim((string)@shell_exec("timeout 60 $exim -bp 2>/dev/null | awk '/frozen/{print \$3}' | xargs -r $exim -Mrm 2>/dev/null | wc -l"));
        smpro_audit('spam_queue_rm_frozen', ['removed' => $n]);
        echo json_encode(['ok' => true, 'msg' => 'Removed ' . $n . ' frozen message(s) from the mail queue.']); exit;
    }
    $sender = strtolower(trim((string)($_POST['sender'] ?? '')));
    if (!filter_var($sender, FILTER_VALIDATE_EMAIL)) { echo json_encode(['ok' => false, 'msg' => 'Invalid sender address.']); exit; }
    $esc = escapeshellarg($sender);
    $n = (int)trim((string)@shell_exec("timeout 90 $exim -bp 2>/dev/null | grep -F $esc | awk '{print \$3}' | xargs -r $exim -Mrm 2>/dev/null | wc -l"));
    smpro_audit('spam_queue_rm_sender', ['sender' => $sender, 'removed' => $n]);
    echo json_encode(['ok' => true, 'msg' => 'Removed ' . $n . ' queued message(s) from ' . $sender . '.']); exit;
}

/* ---------- Email-account outgoing block (POST+CSRF+root) via UAPI Email suspend_outgoing ---------- */
if ($reqMethod === 'POST' && in_array(($_POST['sp_action'] ?? ''), ['mail_block', 'mail_unblock'], true)) {
    smpro_require_valid_csrf('sp_ai'); smpro_require_root();
    header('Content-Type: application/json');
    $email = strtolower(trim((string)($_POST['email'] ?? '')));
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) { echo json_encode(['ok' => false, 'msg' => 'Invalid email address.']); exit; }
    $owner = smpro_sp_owner($email);
    if ($owner === '' || !is_file('/var/cpanel/users/' . $owner)) { echo json_encode(['ok' => false, 'msg' => 'Could not resolve the cPanel owner of ' . $email . '.']); exit; }
    if (!is_executable('/usr/bin/uapi')) { echo json_encode(['ok' => false, 'msg' => 'uapi not available.']); exit; }
